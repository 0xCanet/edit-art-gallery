const {transformInspection,inspectionGesture}=await import('./dist/gallery-math.js');
const viewArea={width:300,height:400};
const baseBounds={left:0,top:0,width:300,height:400};
const pinchStart=[{x:90,y:120},{x:150,y:200}];
const midpoint=points=>({x:(points[0].x+points[1].x)/2,y:(points[0].y+points[1].y)/2});
const artPoint=(point,view)=>({x:view.x+(point.x-150)/(300*view.zoom),y:view.y-(point.y-200)/(400*view.zoom)});
const pinchEnd=[{x:80,y:85},{x:200,y:245}];
const pinched=inspectionGesture(inspectionView(),pinchStart,pinchEnd,baseBounds,viewArea);
assert.equal(pinched.zoom,2);
const anchorBefore=artPoint(midpoint(pinchStart),inspectionView()),anchorAfter=artPoint(midpoint(pinchEnd),pinched);
assert(Math.abs(anchorBefore.x-anchorAfter.x)<1e-12);
assert(Math.abs(anchorBefore.y-anchorAfter.y)<1e-12);
const projected=view=>({left:150-(.5+view.x)*300*view.zoom,top:200-(.5-view.y)*400*view.zoom,width:300*view.zoom,height:400*view.zoom});
const beforeDrag=projected(pinched);
const dragged=inspectionGesture(pinched,[{x:140,y:165}],[{x:170,y:185}],beforeDrag,viewArea);
const afterDrag=projected(dragged);
assert(Math.abs(afterDrag.left-beforeDrag.left-30)<1e-10);
assert(Math.abs(afterDrag.top-beforeDrag.top-20)<1e-10);
const resumed=inspectionGesture(pinched,[{x:170,y:200}],[{x:170,y:200}],beforeDrag,viewArea);
assert(Math.abs(resumed.x-pinched.x)<1e-12&&Math.abs(resumed.y-pinched.y)<1e-12);
const maxPinch=inspectionGesture(inspectionView(),pinchStart,[{x:-1000,y:-1000},{x:1000,y:1000}],baseBounds,viewArea);
assert.equal(maxPinch.zoom,4);
const beyond=inspectionGesture(pinched,[{x:100,y:100}],[{x:9000,y:-9000}],beforeDrag,viewArea);
assert.equal(beyond.x,-.25);assert.equal(beyond.y,-.25);
const resetPinch=transformInspection(pinched,beforeDrag,viewArea,{x:120,y:160},{x:120,y:160},.1);
assert.equal(resetPinch.zoom,1);assert.equal(Math.abs(resetPinch.x)+Math.abs(resetPinch.y),0);
assert(Object.values(inspectionGesture(inspectionView(),[{x:0,y:0},{x:0,y:0}],[{x:0,y:0},{x:0,y:0}],baseBounds,viewArea)).every(Number.isFinite));
